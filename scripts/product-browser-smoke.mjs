// Runs only against the owned Python HTTP fixture; credentials enter via stdin, not argv/files.
import assert from 'node:assert/strict'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadChromium, browserExecutable, browserEnvironment } from './browser-fixture.mjs'
const context = JSON.parse(readFileSync(0, 'utf8'))
assert.match(context.url, /^http:\/\/127\.0\.0\.1:\d+\/$/)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { chromium } = await loadChromium(root)
const executablePath = browserExecutable()
assert(executablePath, 'Set BROWSER_EXECUTABLE to a Chromium executable')
let browser, failure
const errors = [], checks = []
try {
  browser = await chromium.launch({ executablePath, headless: true, chromiumSandbox: true, env: browserEnvironment() })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, reducedMotion: 'reduce' })
  page.on('pageerror', e => errors.push(e.message))
  async function navigatePage(name, group) {
    const target = page.getByRole('button', { name, exact: true })
    if (!await target.isVisible()) await page.getByRole('button', { name: group, exact: true }).click()
    await target.click()
  }
  const responseFor = (ending, method) => page.waitForResponse(r => r.url().endsWith(ending) && r.request().method() === method)
  async function confirmWrite(ending, method = 'POST', needsConfirmation = false) {
    const dialog = page.getByRole('dialog')
    const response = responseFor(ending, method)
    await dialog.locator('button[type=submit]').click()
    if (needsConfirmation) await dialog.locator('button[type=submit]').click()
    const result = await response
    assert.equal(result.status(), 200, `Synthetic UI ${method} ${ending} failed`)
    const body = await result.json()
    await dialog.waitFor({ state: 'hidden' })
    return body
  }
  async function chooseVersion(id) {
    await page.locator('.version-choice').filter({ hasText: id }).click()
  }
  async function runTest(version) {
    await chooseVersion(version.id)
    await page.getByRole('button', { name: '运行合成样例测试', exact: true }).click()
    await page.getByRole('button', { name: '填入四类合成示例（不会自动测试）', exact: true }).click()
    await page.getByRole('dialog').getByRole('checkbox').check()
    const result = await confirmWrite(`/api/management/product-versions/${version.id}/test`)
    assert.equal(result.passed, true)
    assert(result.results.some(row => row.event_type === 'UNKNOWN' && row.battery_percent === null))
    return result
  }
  async function publish(version) {
    await chooseVersion(version.id)
    await page.getByRole('button', { name: '发布此版本', exact: true }).click()
    const dialog = page.getByRole('dialog')
    if (await dialog.getByRole('checkbox').count()) await dialog.getByRole('checkbox').check()
    return confirmWrite(`/api/management/product-versions/${version.id}/publish`, 'POST', true)
  }
  await page.goto(new URL('/management/login', context.url).href)
  await page.getByLabel('账户', { exact: true }).fill(context.username)
  await page.getByLabel('密码', { exact: true }).fill(context.password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await navigatePage('单位位置', '单位与场所')
  await page.getByRole('combobox', { name: '选择租户' }).selectOption(context.tenant_id)
  await navigatePage('产品模板', '设备资源')
  await page.getByRole('button', { name: '创建产品', exact: true }).click()
  await page.getByLabel('产品名称', { exact: true }).fill('浏览器合成版本产品')
  await page.getByLabel('厂商标识', { exact: true }).fill('BROWSER_SYNTHETIC_ONLY')
  await page.getByLabel('型号标识', { exact: true }).fill('BROWSER-MODEL-JSON')
  await page.getByLabel('产品描述', { exact: true }).fill('合成模板，不代表真实品牌已接通')
  const product = await confirmWrite('/api/management/products')
  await page.getByRole('row').filter({ hasText: '浏览器合成版本产品' }).getByRole('button', { name: '查看版本', exact: true }).click()
  await page.getByRole('button', { name: '创建空白草稿', exact: true }).click()
  let version1 = await confirmWrite(`/api/management/products/${product.id}/versions`)
  await chooseVersion(version1.id)
  assert.equal(await page.getByRole('button', { name: '发布此版本', exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: '编辑草稿', exact: true }).click()
  const mapping = { format: 'JSON_POINTER_V1', event_pointer: '/event', event_mappings: [{ raw_value: 'FIRE', event_type: 'FIRE' }, { raw_value: 'RECOVERY', event_type: 'RECOVERY' }], battery: { pointer: '/battery', scale: 1, offset: 0, min: 0, max: 100 } }
  await page.getByLabel('Schema JSON', { exact: true }).fill(JSON.stringify(mapping, null, 2))
  for (const name of ['火警能力', '恢复能力', '电量能力']) await page.getByRole('combobox', { name }).selectOption('SUPPORTED')
  version1 = await confirmWrite(`/api/management/product-versions/${version1.id}`, 'PUT')
  await runTest(version1)
  version1 = await publish(version1)
  assert.equal(version1.status, 'PUBLISHED')
  await chooseVersion(version1.id)
  assert.equal(await page.getByRole('button', { name: '编辑草稿', exact: true }).isDisabled(), true)
  assert.equal(await page.getByRole('button', { name: '运行合成样例测试', exact: true }).isDisabled(), true)
  await page.waitForFunction(() => { const node = document.querySelector('#main-content > div'); return node && getComputedStyle(node).opacity === '1' })
  await page.screenshot({ path: path.join(context.artifact_directory, 'product-versions.png'), fullPage: true, animations: 'disabled' })
  checks.push('global product create, explicit capabilities, synthetic test evidence and immutable publish in real UI')
  await navigatePage('设备监测', '设备资源')
  await page.getByRole('button', { name: '正式设备开户', exact: true }).click()
  await page.getByLabel('设备名称', { exact: true }).fill('浏览器开户设备')
  await page.getByLabel('安装地址', { exact: true }).fill('合成测试位置')
  await page.getByLabel('所属位置（必选）', { exact: true }).selectOption(context.place_id)
  await page.getByLabel('设备EUI / 标识', { exact: true }).fill('BROWSER-P3-EUI')
  await page.getByLabel('产品', { exact: true }).selectOption(product.id)
  assert.equal(await page.getByLabel('具体已发布版本', { exact: true }).inputValue(), '')
  await page.getByLabel('具体已发布版本', { exact: true }).selectOption(version1.id)
  let device = await confirmWrite('/api/management/devices')
  assert.equal(device.physical_state, 'UNKNOWN')
  assert.equal(device.connectivity, 'UNACTIVATED')
  assert.equal(device.is_simulated, false)
  assert.equal(device.battery_percent, null)
  let row = page.getByRole('row').filter({ hasText: 'BROWSER-P3-EUI' })
  await row.waitFor()
  assert.equal(await row.locator('.status-success').count(), 0)
  assert.equal(await row.getByText('正常', { exact: true }).count(), 0)
  await row.getByRole('button', { name: '更多设备操作', exact: true }).click()
  await page.getByRole('button', { name: '编辑资料', exact: true }).click()
  await page.getByLabel('设备名称', { exact: true }).fill('浏览器开户设备（已改名）')
  await page.getByLabel('所属位置（必选）', { exact: true }).selectOption(context.move_place_id)
  device = await confirmWrite(`/api/management/devices/${device.id}`, 'PUT')
  await row.getByRole('button', { name: '绑定历史', exact: true }).click()
  await page.getByRole('dialog').getByText('正式开户绑定', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await row.getByRole('button', { name: '位置历史', exact: true }).click()
  const placementDialog = page.getByRole('dialog')
  await placementDialog.getByRole('heading', { name: '设备位置变更历史', exact: true }).waitFor()
  await placementDialog.getByText(context.move_place_name, { exact: false }).waitFor()
  assert.equal(await placementDialog.getByRole('listitem').count(), 2)
  await placementDialog.getByText('开户初始位置', { exact: true }).waitFor()
  await placementDialog.getByText('同单位位置移动', { exact: true }).waitFor()
  await page.screenshot({ path: path.join(context.artifact_directory, 'device-place-history-desktop.png'), fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: path.join(context.artifact_directory, 'device-place-history-mobile.png'), fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  checks.push('position change history shows initial placement and actual same-unit move with immutable place names in desktop and mobile UI')
  checks.push('explicit published version onboarding, default real/pending/UNKNOWN/null, metadata edit and REGISTER history')

  await navigatePage('产品模板', '设备资源')
  await page.getByRole('row').filter({ hasText: '浏览器合成版本产品' }).getByRole('button', { name: '查看版本', exact: true }).click()
  await chooseVersion(version1.id)
  await page.getByRole('button', { name: '复制成新草稿', exact: true }).click()
  let version2 = await confirmWrite(`/api/management/products/${product.id}/versions`)
  assert.equal(version2.parser_tested, false)
  await runTest(version2)
  version2 = await publish(version2)
  assert(version2.version_number > version1.version_number)
  await navigatePage('设备监测', '设备资源')
  row = page.getByRole('row').filter({ hasText: 'BROWSER-P3-EUI' })
  await row.getByRole('button', { name: '迁移版本', exact: true }).click()
  await page.getByLabel('具体已发布版本', { exact: true }).selectOption(version2.id)
  await page.getByLabel('版本迁移原因', { exact: true }).fill('浏览器显式迁移合成验收，不表示设备恢复')
  const migrated = await confirmWrite(`/api/management/devices/${device.id}/migrate-version`, 'POST', true)
  assert.equal(migrated.product_version_id, version2.id)
  assert.equal(migrated.physical_state, 'UNKNOWN')
  assert.equal(migrated.last_message_at, null)
  await row.getByRole('button', { name: '绑定历史', exact: true }).click()
  await page.getByRole('dialog').getByText('正式开户绑定', { exact: true }).waitFor()
  await page.getByRole('dialog').getByText('显式版本迁移', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.waitForFunction(() => { const node = document.querySelector('#main-content > div'); return node && getComputedStyle(node).opacity === '1' })
  await page.screenshot({ path: path.join(context.artifact_directory, 'device-onboarding.png'), fullPage: true, animations: 'disabled' })
  checks.push('clone clears evidence; new publish leaves existing binding pinned; explicit migration preserves unknown facts and adds history')
  assert.equal(await page.locator('input[type=password]').count(), 0)
  const storage = await page.evaluate(() => ({ local: Object.keys(localStorage), session: Object.keys(sessionStorage) }))
  assert.deepEqual(storage, { local: [], session: [] })
  assert.deepEqual(errors, [])
  const report = { status: 'passed', checks, real_vendor_calls: 0 }
  writeFileSync(path.join(context.artifact_directory, 'browser-result.json'), JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} catch (error) {
  failure = String(error?.stack ?? error).replaceAll(context.password, '[REDACTED]')
} finally {
  if (browser) await browser.close()
}
if (failure) { console.error(failure); process.exitCode = 1 }
